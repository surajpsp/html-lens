package app.htmllens.core.analysis

import app.htmllens.core.bundle.Bundle
import app.htmllens.core.util.Paths
import app.htmllens.core.util.latin1
import kotlinx.serialization.Serializable

@Serializable
data class ExportType(val id: String, val label: String, val hint: String, val searchable: Boolean = true)

/** Recognises well-known HTML exports and reports so the UI can offer tailored tools. */
object ExportDetector {

    fun detect(bundle: Bundle): ExportType? {
        val paths = bundle.files.keys
        val names = paths.map { Paths.basename(it).lowercase() }.toSet()
        val entryHead = bundle.files[bundle.entry]?.let { it.bytes.latin1(0, minOf(it.size, 16_384)).lowercase() } ?: ""

        return when {
            paths.any { Regex("(^|/)messages\\d*\\.html$").containsMatchIn(it) } && (entryHead.contains("page_wrap") || names.contains("script.js")) ->
                ExportType("telegram", "Telegram chat export", "Search every message across all pages of this chat.")
            paths.any { it.contains("your_facebook_activity/") || it.contains("facebook-") && it.endsWith(".html") } ->
                ExportType("facebook", "Facebook data export", "Search posts, messages and activity across the whole export.")
            paths.any { it.contains("your_instagram_activity/") } || entryHead.contains("instagram") && paths.any { it.contains("messages/inbox/") } ->
                ExportType("instagram", "Instagram data export", "Search messages and activity across the whole export.")
            names.contains("archive_browser.html") || paths.any { it.startsWith("Takeout/") } ->
                ExportType("takeout", "Google Takeout", "Browse and search the HTML parts of your Google data.")
            names.contains("your archive.html") || (paths.any { it.startsWith("data/") } && entryHead.contains("twitter")) ->
                ExportType("x", "X (Twitter) archive", "Browse your archive offline.")
            names.contains("jacoco-sessions.html") || entryHead.contains("jacoco") ->
                ExportType("jacoco", "JaCoCo coverage report", "Coverage report with working navigation.", searchable = false)
            entryHead.contains("test summary") && paths.any { it.startsWith("classes/") || it.contains("/classes/") } ->
                ExportType("gradle-tests", "Gradle test report", "Test results with working navigation.", searchable = false)
            entryHead.contains("playwright") && names.contains("index.html") ->
                ExportType("playwright", "Playwright test report", "Open traces and results offline.", searchable = false)
            entryHead.contains("allure") ->
                ExportType("allure", "Allure report", "Interactive test report.", searchable = false)
            entryHead.contains("lighthouse") ->
                ExportType("lighthouse", "Lighthouse report", "Performance audit report.", searchable = false)
            entryHead.contains("lint report") || names.any { it.startsWith("lint-results") } ->
                ExportType("android-lint", "Android Lint report", "Lint findings with working links.", searchable = false)
            entryHead.contains("generator\" content=\"javadoc") || entryHead.contains("<!-- generated by javadoc") || names.contains("allclasses-index.html") ->
                ExportType("javadoc", "API documentation", "Search across every documentation page.")
            entryHead.contains("notion") && bundle.htmlFiles.size > 1 ->
                ExportType("notion", "Notion export", "Search across all exported pages.")
            bundle.htmlFiles.size >= 3 -> ExportType("site", "Multi-page site", "Search across all ${bundle.htmlFiles.size} pages.")
            else -> null
        }
    }
}
